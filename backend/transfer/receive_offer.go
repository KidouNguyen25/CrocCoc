package transfer

import (
	"crypto/rand"
	"encoding/hex"
	"strconv"
	"strings"
	"time"
)

const OfferDecisionTimeout = 2 * time.Minute

// ReceiveOffer is a sanitized, copyable view of an untrusted peer manifest.
// It is metadata only: constructing an offer never authorizes payload download.
type ReceiveOffer struct {
	OfferID    string      `json:"offerID"`
	Items      []OfferItem `json:"items"`
	FileCount  int         `json:"fileCount"`
	TotalBytes string      `json:"totalBytes"`
	ExpiresAt  time.Time   `json:"expiresAt"`
}

// OfferItem carries only relative paths and validated metadata, never the
// sender's absolute path or raw engine output.
type OfferItem struct {
	Path      string `json:"path"`
	Type      string `json:"type"`
	SizeBytes string `json:"sizeBytes,omitempty"`
}

// PrepareReceiveOffer validates names and quotas, issues an unpredictable
// offer ID, and takes a defensive copy of the presented metadata.
// Destination handle, alias, free-space and conflict preflight is separate;
// callers MUST complete it before offering or approving any transfer.
func PrepareReceiveOffer(entries []ManifestEntry, now time.Time) (ReceiveOffer, error) {
	total, err := ValidateManifest(entries)
	if err != nil {
		return ReceiveOffer{}, err
	}
	var random [16]byte
	if _, err := rand.Read(random[:]); err != nil {
		return ReceiveOffer{}, ErrUnsafeOffer
	}
	offer := ReceiveOffer{
		OfferID:    hex.EncodeToString(random[:]),
		Items:      make([]OfferItem, 0, len(entries)),
		TotalBytes: strconv.FormatInt(total, 10),
		ExpiresAt:  now.Add(OfferDecisionTimeout).UTC(),
	}
	for _, entry := range entries {
		item := OfferItem{Path: strings.ReplaceAll(entry.Path, "\\", "/")}
		if entry.Directory {
			item.Type = "directory"
		} else {
			item.Type = "file"
			item.SizeBytes = strconv.FormatInt(entry.SizeBytes, 10)
			offer.FileCount++
		}
		offer.Items = append(offer.Items, item)
	}
	return offer, nil
}

// Clone prevents consumers of a snapshot from mutating the coordinator's
// stored offer. A new offer ID is only generated by PrepareReceiveOffer.
func (o ReceiveOffer) Clone() ReceiveOffer {
	copyOffer := o
	copyOffer.Items = append([]OfferItem(nil), o.Items...)
	return copyOffer
}

func (o ReceiveOffer) Expired(now time.Time) bool {
	return !now.Before(o.ExpiresAt)
}
